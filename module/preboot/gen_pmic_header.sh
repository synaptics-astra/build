#!/bin/bash

PMIC_MODELS_CONF="${CONFIG_SYNA_SDK_PATH}/build/module/preboot/pmic_models"
OUTPUT_H=${CONFIG_SYNA_SDK_PATH}/boot/common/driver/pmic/pmic_autogen.h

if [ ! -f "$PMIC_MODELS_CONF" ]; then
    echo "Error: PMIC models configuration file not found at $PMIC_MODELS_CONF" >&2
    (return 0 2>/dev/null) && return 1 || exit 1
fi

mkdir -p "$(dirname "$OUTPUT_H")"

{
    echo "/* Autogenerated PMIC configuration - DO NOT EDIT */"
    echo "#ifndef _PMIC_AUTOGEN_H_"
    echo "#define _PMIC_AUTOGEN_H_"
    echo ""

    # Generate Enum
    echo "typedef enum {"
    _id=1
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        [[ "$name" =~ ^#.* ]] && continue
        [[ -z "$name" ]] && continue
        name=$(echo $name | xargs)
        NAME_UPPER=$(echo "$name" | tr '[:lower:]' '[:upper:]')

        if [ "$NAME_UPPER" = "UNKNOWN" ]; then continue; fi

        _val=$((_id - 1))
        echo "	${NAME_UPPER} = ${_val},"
        _id=$((_id + 1))
    done < "$PMIC_MODELS_CONF"
    echo "	PMIC_UNKNOW,"
    echo "} PMIC_CHIP_SELECTION_AUTOGEN;"
    echo ""

    # Generate Names Array
    echo "#define PMIC_MODEL_NAMES_AUTOGEN \\"
    echo "	[0] = \"unknown\", \\"
    _id=1
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        [[ "$name" =~ ^#.* ]] && continue
        [[ -z "$name" ]] && continue
        name=$(echo $name | xargs | tr '[:upper:]' '[:lower:]')
        if [ "$name" = "unknown" ]; then continue; fi

        echo "	[${_id}] = \"${name}\", \\"
        _id=$((_id + 1))
    done < "$PMIC_MODELS_CONF"
    echo ""

    # Generate Driver Ops Mapping
    echo "#define PMIC_DVFS_OPS_SWITCH_AUTOGEN(pmic_id, dvfs_ops) \\"
    echo "    switch (pmic_id) { \\"

    _processed_aliases=""
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        [[ "$name" =~ ^#.* ]] && continue
        [[ -z "$name" ]] && continue
        alias=$(echo $alias | xargs | tr '[:upper:]' '[:lower:]')
        [ "$(echo "$name" | tr '[:lower:]' '[:upper:]')" = "UNKNOWN" ] && continue

        case " $_processed_aliases " in (*" $alias "*) continue;; esac
        _processed_aliases="$_processed_aliases $alias"

        _cases=""
        while IFS=', ' read -r n a || [ -n "$n" ]; do
            [[ "$n" =~ ^#.* ]] && continue
            [[ -z "$n" ]] && continue
            n=$(echo $n | xargs); a=$(echo $a | xargs | tr '[:upper:]' '[:lower:]')
            if [ "$a" = "$alias" ]; then
                NU=$(echo "$n" | tr '[:lower:]' '[:upper:]')
                if [ "$NU" != "UNKNOWN" ]; then
                    _cases="${_cases}case $NU:"
                fi
            fi
        done < "$PMIC_MODELS_CONF"

        if [ -n "$_cases" ]; then
            echo "		$_cases dvfs_ops = &${alias}_ops; break; \\"
        fi
    done < "$PMIC_MODELS_CONF"

    echo "		case PMIC_UNKNOW: break; \\"
    echo "		default: ERR(\"Error! Unsupported PMIC for pv_comp!\\n\"); break; \\"
    echo "	}"
    echo ""
    echo "#endif"
} > "$OUTPUT_H"
