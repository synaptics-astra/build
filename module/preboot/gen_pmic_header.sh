#!/bin/sh

if [ "$#" -ne 1 ]; then
    printf 'Usage: %s SDK_PATH\n' "$0" >&2
    exit 2
fi

sdk_path=$1
PMIC_MODELS_CONF="${sdk_path}/build/module/preboot/pmic_models"
OUTPUT_H="${sdk_path}/boot/common/driver/pmic/pmic_autogen.h"

if [ ! -f "$PMIC_MODELS_CONF" ]; then
    printf 'Error: PMIC models configuration file not found at %s\n' \
        "$PMIC_MODELS_CONF" >&2
    exit 1
fi

mkdir -p "$(dirname "$OUTPUT_H")"

{
    printf '%s\n' '/* Autogenerated PMIC configuration - DO NOT EDIT */'
    printf '%s\n' '#ifndef _PMIC_AUTOGEN_H_'
    printf '%s\n' '#define _PMIC_AUTOGEN_H_'
    printf '\n'

    # Generate Enum
    printf '%s\n' 'typedef enum {'
    _id=1
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        case $name in
            ''|\#*) continue ;;
        esac
        name=$(printf '%s\n' "$name" | xargs)
        NAME_UPPER=$(printf '%s\n' "$name" | tr '[:lower:]' '[:upper:]')

        if [ "$NAME_UPPER" = "UNKNOWN" ]; then continue; fi

        _val=$((_id - 1))
        printf '\t%s = %s,\n' "$NAME_UPPER" "$_val"
        _id=$((_id + 1))
    done < "$PMIC_MODELS_CONF"
    printf '\t%s\n' 'PMIC_UNKNOW,'
    printf '%s\n' '} PMIC_CHIP_SELECTION_AUTOGEN;'
    printf '\n'

    # Generate Names Array
    printf '%s\n' '#define PMIC_MODEL_NAMES_AUTOGEN \'
    printf '\t%s\n' '[0] = "unknown", \'
    _id=1
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        case $name in
            ''|\#*) continue ;;
        esac
        name=$(printf '%s\n' "$name" | xargs | tr '[:upper:]' '[:lower:]')
        if [ "$name" = "unknown" ]; then continue; fi

        printf '\t[%s] = "%s", \\\n' "$_id" "$name"
        _id=$((_id + 1))
    done < "$PMIC_MODELS_CONF"
    printf '\n'

    # Generate Driver Ops Mapping
    printf '%s\n' '#define PMIC_DVFS_OPS_SWITCH_AUTOGEN(pmic_id, dvfs_ops) \'
    printf '%s\n' '    switch (pmic_id) { \'

    _processed_aliases=""
    while IFS=', ' read -r name alias || [ -n "$name" ]; do
        case $name in
            ''|\#*) continue ;;
        esac
        alias=$(printf '%s\n' "$alias" | xargs | tr '[:upper:]' '[:lower:]')
        [ "$(printf '%s\n' "$name" | tr '[:lower:]' '[:upper:]')" = "UNKNOWN" ] && continue

        case " $_processed_aliases " in (*" $alias "*) continue;; esac
        _processed_aliases="$_processed_aliases $alias"

        _cases=""
        while IFS=', ' read -r n a || [ -n "$n" ]; do
            case $n in
                ''|\#*) continue ;;
            esac
            n=$(printf '%s\n' "$n" | xargs)
            a=$(printf '%s\n' "$a" | xargs | tr '[:upper:]' '[:lower:]')
            if [ "$a" = "$alias" ]; then
                NU=$(printf '%s\n' "$n" | tr '[:lower:]' '[:upper:]')
                if [ "$NU" != "UNKNOWN" ]; then
                    _cases="${_cases}case $NU:"
                fi
            fi
        done < "$PMIC_MODELS_CONF"

        if [ -n "$_cases" ]; then
            printf '\t\t%s dvfs_ops = &%s_ops; break; \\\n' "$_cases" "$alias"
        fi
    done < "$PMIC_MODELS_CONF"

    printf '\t\t%s\n' 'case PMIC_UNKNOW: break; \'
    printf '\t\t%s\n' 'default: ERR("Error! Unsupported PMIC for pv_comp!\n"); break; \'
    printf '\t%s\n' '}'
    printf '\n'
    printf '%s\n' '#endif'
} > "${OUTPUT_H}.tmp" && mv "${OUTPUT_H}.tmp" "$OUTPUT_H"
